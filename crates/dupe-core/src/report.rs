//! Rendering a scan as a self-contained HTML document.
//!
//! Everything is inlined — styles, and the photo thumbnails as data URLs — so
//! the file survives being emailed, dropped on a share, or opened in two years
//! by someone who no longer has the app. There is no JavaScript: a report that
//! needs a runtime to be read is not an archive.
//!
//! A print stylesheet comes with it, because "print this" is usually what a
//! report is for and browsers make a poor job of it unaided.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::model::{DuplicateGroup, SimilarGroup};
use crate::orphans::{Confidence, OrphanFinding, OrphanKind};
use crate::progress::Summary;

pub struct ReportInput<'a> {
    /// Seconds since the unix epoch.
    pub generated_at: i64,
    pub roots: &'a [PathBuf],
    pub summary: &'a Summary,
    pub duplicates: &'a [DuplicateGroup],
    pub similar: &'a [SimilarGroup],
    pub orphans: &'a [OrphanFinding],
    pub options: ReportOptions,
}

#[derive(Debug, Clone, Copy)]
pub struct ReportOptions {
    /// Embed photo previews as data URLs.
    ///
    /// Without them the photo section is a list of paths, which is close to
    /// useless for judging whether four pictures are the same picture. With
    /// them the file grows by a couple of kilobytes per photo, so the number
    /// of clusters is capped.
    pub include_thumbnails: bool,
    /// How many photo clusters to illustrate before falling back to a list.
    pub max_illustrated_clusters: usize,
}

impl Default for ReportOptions {
    fn default() -> Self {
        Self {
            include_thumbnails: true,
            max_illustrated_clusters: 200,
        }
    }
}

/// Pixel size of an embedded preview. Small on purpose: at 96 pixels a JPEG is
/// two or three kilobytes, and the report stays a file rather than a download.
const THUMBNAIL_SIZE: u32 = 96;

pub fn to_html(input: &ReportInput) -> String {
    let mut out = String::with_capacity(1 << 16);

    out.push_str("<!doctype html>\n<html lang=\"en\">\n<head>\n");
    out.push_str("<meta charset=\"utf-8\">\n");
    out.push_str("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n");
    let _ = writeln!(
        out,
        "<title>Duplicate Finder report — {}</title>",
        escape(&format_date(input.generated_at))
    );
    out.push_str(STYLE);
    out.push_str("</head>\n<body>\n");

    header(&mut out, input);
    summary_cards(&mut out, input.summary, input.orphans);
    duplicates_section(&mut out, input.duplicates);
    photos_section(&mut out, input.similar, input.options);
    orphans_section(&mut out, input.orphans);

    out.push_str("<footer>Generated by Duplicate Finder. Nothing in this report has been deleted.</footer>\n");
    out.push_str("</body>\n</html>\n");
    out
}

fn header(out: &mut String, input: &ReportInput) {
    out.push_str("<header>\n<h1>Duplicate Finder report</h1>\n");
    let _ = writeln!(
        out,
        "<p class=\"meta\">{}</p>",
        escape(&format_date_time(input.generated_at))
    );

    if !input.roots.is_empty() {
        out.push_str("<p class=\"meta\">Scanned: ");
        let names: Vec<String> = input
            .roots
            .iter()
            .map(|r| format!("<code>{}</code>", escape(&r.to_string_lossy())))
            .collect();
        out.push_str(&names.join(", "));
        out.push_str("</p>\n");
    }
    out.push_str("</header>\n");
}

fn summary_cards(out: &mut String, summary: &Summary, orphans: &[OrphanFinding]) {
    let orphan_bytes: u64 = orphans.iter().map(|f| f.size_bytes).sum();

    out.push_str("<section class=\"cards\">\n");
    card(out, "Files examined", &thousands(summary.files_seen), None);
    card(
        out,
        "Reclaimable",
        &human_bytes(summary.wasted_bytes + orphan_bytes),
        Some("across duplicates and orphans"),
    );
    card(
        out,
        "Duplicate groups",
        &thousands(summary.duplicate_groups),
        Some(&format!("{} files", thousands(summary.duplicate_files))),
    );
    card(
        out,
        "Look-alike clusters",
        &thousands(summary.similar_groups),
        Some(&format!("{} photos", thousands(summary.similar_images))),
    );
    card(out, "Orphans", &thousands(orphans.len() as u64), None);
    card(
        out,
        "Scan time",
        &format_duration(summary.elapsed_ms),
        (summary.skipped > 0)
            .then(|| format!("{} skipped", thousands(summary.skipped)))
            .as_deref(),
    );
    out.push_str("</section>\n");
}

fn card(out: &mut String, label: &str, value: &str, note: Option<&str>) {
    let _ = write!(
        out,
        "<div class=\"card\"><span class=\"label\">{}</span><span class=\"value\">{}</span>",
        escape(label),
        escape(value)
    );
    if let Some(note) = note {
        let _ = write!(out, "<span class=\"note\">{}</span>", escape(note));
    }
    out.push_str("</div>\n");
}

fn duplicates_section(out: &mut String, groups: &[DuplicateGroup]) {
    out.push_str("<section>\n<h2>Identical files</h2>\n");

    if groups.is_empty() {
        out.push_str("<p class=\"empty\">None found.</p>\n</section>\n");
        return;
    }

    for group in groups {
        out.push_str("<article class=\"group\">\n<h3>");
        let _ = write!(
            out,
            "{} each <span class=\"note\">· {} copies · {} wasted</span>",
            escape(&human_bytes(group.size)),
            group.files.len(),
            escape(&human_bytes(group.wasted_bytes()))
        );
        out.push_str("</h3>\n<table>\n");
        out.push_str(
            "<thead><tr><th>Path</th><th class=\"right\">Modified</th></tr></thead>\n<tbody>\n",
        );

        for file in &group.files {
            let _ = writeln!(
                out,
                "<tr><td><code>{}</code></td><td class=\"right\">{}</td></tr>",
                escape(&file.path.to_string_lossy()),
                escape(&format_date(file.mtime))
            );
        }

        out.push_str("</tbody>\n</table>\n</article>\n");
    }

    out.push_str("</section>\n");
}

fn photos_section(out: &mut String, groups: &[SimilarGroup], options: ReportOptions) {
    out.push_str("<section>\n<h2>Look-alike photos</h2>\n");

    if groups.is_empty() {
        out.push_str("<p class=\"empty\">None found.</p>\n</section>\n");
        return;
    }

    for (index, group) in groups.iter().enumerate() {
        let illustrate = options.include_thumbnails && index < options.max_illustrated_clusters;

        out.push_str("<article class=\"group\">\n<h3>");
        let _ = write!(
            out,
            "{} similar photos <span class=\"note\">· {} total</span>",
            group.images.len(),
            escape(&human_bytes(group.images.iter().map(|i| i.file.size).sum()))
        );
        out.push_str("</h3>\n");

        if illustrate {
            out.push_str("<div class=\"tiles\">\n");
            for image in &group.images {
                out.push_str("<figure>\n");
                match thumbnail_data_url(&image.file.path) {
                    Some(src) => {
                        let _ = writeln!(
                            out,
                            "<img src=\"{}\" alt=\"{}\">",
                            src,
                            escape(&file_name(&image.file.path))
                        );
                    }
                    None => out.push_str("<div class=\"missing\"></div>\n"),
                }
                let _ = writeln!(
                    out,
                    "<figcaption><strong>{}</strong><br>{}×{} · {}<br>{}</figcaption>",
                    escape(&file_name(&image.file.path)),
                    image.width,
                    image.height,
                    escape(&human_bytes(image.file.size)),
                    if image.distance == 0 {
                        "identical".to_string()
                    } else {
                        format!("{}% match", 100 - (image.distance * 100 / 64).min(100))
                    }
                );
                out.push_str("</figure>\n");
            }
            out.push_str("</div>\n");
        }

        out.push_str("<table>\n<thead><tr><th>Path</th><th class=\"right\">Size</th><th class=\"right\">Taken</th></tr></thead>\n<tbody>\n");
        for image in &group.images {
            let _ = writeln!(
                out,
                "<tr><td><code>{}</code></td><td class=\"right\">{}</td><td class=\"right\">{}</td></tr>",
                escape(&image.file.path.to_string_lossy()),
                escape(&human_bytes(image.file.size)),
                escape(&format_date(image.taken_at.unwrap_or(image.file.mtime)))
            );
        }
        out.push_str("</tbody>\n</table>\n</article>\n");
    }

    if options.include_thumbnails && groups.len() > options.max_illustrated_clusters {
        let _ = writeln!(
            out,
            "<p class=\"note\">Previews are shown for the first {} clusters; the rest are listed by path to keep the file a reasonable size.</p>",
            options.max_illustrated_clusters
        );
    }

    out.push_str("</section>\n");
}

fn orphans_section(out: &mut String, findings: &[OrphanFinding]) {
    out.push_str("<section>\n<h2>Orphans</h2>\n");

    if findings.is_empty() {
        out.push_str("<p class=\"empty\">None found.</p>\n</section>\n");
        return;
    }

    out.push_str("<p class=\"note\">Confidence matters here: only <em>verified</em> findings were checked directly against the file system. The rest are judgements, and the reason is given for each.</p>\n");
    out.push_str("<table>\n<thead><tr><th>Kind</th><th>Path</th><th>Why</th><th class=\"right\">Size</th><th>Confidence</th></tr></thead>\n<tbody>\n");

    for finding in findings {
        let _ = writeln!(
            out,
            "<tr><td>{}</td><td><code>{}</code></td><td class=\"reason\">{}</td><td class=\"right\">{}</td><td><span class=\"pill {}\">{}</span></td></tr>",
            escape(kind_label(finding.kind)),
            escape(&finding.path.to_string_lossy()),
            escape(&finding.reason),
            escape(&human_bytes(finding.size_bytes)),
            confidence_class(finding.confidence),
            escape(confidence_label(finding.confidence)),
        );
    }

    out.push_str("</tbody>\n</table>\n</section>\n");
}

fn thumbnail_data_url(path: &Path) -> Option<String> {
    use std::io::Cursor;

    let preview = crate::images::decode::load_preview(path, THUMBNAIL_SIZE).ok()?;
    let buffer = image::RgbImage::from_raw(preview.width, preview.height, preview.rgb)?;

    let mut encoded = Cursor::new(Vec::new());
    image::codecs::jpeg::JpegEncoder::new_with_quality(&mut encoded, 70)
        .encode_image(&buffer)
        .ok()?;

    Some(format!(
        "data:image/jpeg;base64,{}",
        base64(&encoded.into_inner())
    ))
}

/// Standard base64, no line breaks. A dependency would do, but this is the
/// only place the crate needs one.
fn base64(bytes: &[u8]) -> String {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

    let mut out = String::with_capacity(bytes.len().div_ceil(3) * 4);

    for chunk in bytes.chunks(3) {
        let b = [
            chunk[0],
            *chunk.get(1).unwrap_or(&0),
            *chunk.get(2).unwrap_or(&0),
        ];
        let n = ((b[0] as u32) << 16) | ((b[1] as u32) << 8) | b[2] as u32;

        out.push(ALPHABET[(n >> 18 & 63) as usize] as char);
        out.push(ALPHABET[(n >> 12 & 63) as usize] as char);
        out.push(if chunk.len() > 1 {
            ALPHABET[(n >> 6 & 63) as usize] as char
        } else {
            '='
        });
        out.push(if chunk.len() > 2 {
            ALPHABET[(n & 63) as usize] as char
        } else {
            '='
        });
    }

    out
}

/// Render the findings as one CSV, for people who would rather sort and pivot
/// than read.
///
/// One row per file with a `kind` column, rather than three separate files:
/// a spreadsheet can filter that in one click, and totals across all three
/// kinds are what the question "how much can I get back" actually needs.
pub fn to_csv(input: &ReportInput, separator: char) -> String {
    let mut out = String::with_capacity(1 << 16);

    // A BOM so Excel reads it as UTF-8 rather than the system codepage, which
    // is what mangles accented folder names.
    out.push('\u{feff}');

    row(
        &mut out,
        separator,
        &[
            "kind",
            "group",
            "path",
            "size_bytes",
            "size",
            "modified",
            "taken",
            "detail",
            "confidence",
        ],
    );

    for group in input.duplicates {
        for file in &group.files {
            row(
                &mut out,
                separator,
                &[
                    "duplicate",
                    &group.id.to_string(),
                    &file.path.to_string_lossy(),
                    &file.size.to_string(),
                    &human_bytes(file.size),
                    &format_date(file.mtime),
                    "",
                    &group.hash.to_hex(),
                    "",
                ],
            );
        }
    }

    for group in input.similar {
        for image in &group.images {
            row(
                &mut out,
                separator,
                &[
                    "photo",
                    &group.id.to_string(),
                    &image.file.path.to_string_lossy(),
                    &image.file.size.to_string(),
                    &human_bytes(image.file.size),
                    &format_date(image.file.mtime),
                    &image.taken_at.map(format_date).unwrap_or_default(),
                    &format!(
                        "{}x{}, {}",
                        image.width,
                        image.height,
                        if image.distance == 0 {
                            "identical".to_string()
                        } else {
                            format!("{}% match", 100 - (image.distance * 100 / 64).min(100))
                        }
                    ),
                    "",
                ],
            );
        }
    }

    for finding in input.orphans {
        row(
            &mut out,
            separator,
            &[
                "orphan",
                "",
                &finding.path.to_string_lossy(),
                &finding.size_bytes.to_string(),
                &human_bytes(finding.size_bytes),
                &finding.last_modified.map(format_date).unwrap_or_default(),
                "",
                &format!("{}: {}", kind_label(finding.kind), finding.reason),
                confidence_label(finding.confidence),
            ],
        );
    }

    out
}

fn row(out: &mut String, separator: char, fields: &[&str]) {
    for (i, field) in fields.iter().enumerate() {
        if i > 0 {
            out.push(separator);
        }
        out.push_str(&csv_field(field, separator));
    }
    // CRLF, which is what RFC 4180 specifies and what Excel is happiest with.
    out.push_str("\r\n");
}

/// Quote a field when it contains the separator, a quote, or a line break —
/// and double any quotes inside it, per RFC 4180.
fn csv_field(value: &str, separator: char) -> String {
    let needs_quotes = value.contains(separator)
        || value.contains('"')
        || value.contains('\n')
        || value.contains('\r');

    if !needs_quotes {
        return value.to_string();
    }

    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for c in value.chars() {
        if c == '"' {
            out.push('"');
        }
        out.push(c);
    }
    out.push('"');
    out
}

fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            _ => out.push(c),
        }
    }
    out
}

fn file_name(path: &Path) -> String {
    path.file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_else(|| path.to_string_lossy().into_owned())
}

fn kind_label(kind: OrphanKind) -> &'static str {
    match kind {
        OrphanKind::BrokenShortcut => "Broken shortcut",
        OrphanKind::EmptyFolder => "Empty folder",
        OrphanKind::LeftoverAppData => "Leftover app data",
        OrphanKind::OrphanedInstallerPackage => "Orphaned installer package",
    }
}

fn confidence_label(confidence: Confidence) -> &'static str {
    match confidence {
        Confidence::Certain => "Verified",
        Confidence::Likely => "Likely",
        Confidence::Suspected => "Suspected",
    }
}

fn confidence_class(confidence: Confidence) -> &'static str {
    match confidence {
        Confidence::Certain => "certain",
        Confidence::Likely => "likely",
        Confidence::Suspected => "suspected",
    }
}

pub fn human_bytes(value: u64) -> String {
    const UNITS: [&str; 6] = ["B", "KB", "MB", "GB", "TB", "PB"];
    if value < 1024 {
        return format!("{value} B");
    }

    let mut scaled = value as f64;
    let mut unit = 0;
    while scaled >= 1024.0 && unit < UNITS.len() - 1 {
        scaled /= 1024.0;
        unit += 1;
    }
    format!("{scaled:.*} {}", usize::from(scaled < 10.0), UNITS[unit])
}

fn thousands(value: u64) -> String {
    let digits = value.to_string();
    let mut out = String::with_capacity(digits.len() + digits.len() / 3);

    for (i, c) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i) % 3 == 0 {
            out.push('.');
        }
        out.push(c);
    }
    out
}

fn format_duration(ms: u64) -> String {
    if ms < 1000 {
        return format!("{ms} ms");
    }
    let seconds = ms / 1000;
    if seconds < 60 {
        return format!("{:.1} s", ms as f64 / 1000.0);
    }
    format!("{}m {}s", seconds / 60, seconds % 60)
}

fn format_date(seconds: i64) -> String {
    if seconds <= 0 {
        return "—".to_string();
    }
    let (year, month, day) = civil_from_unix(seconds);
    format!("{year:04}-{month:02}-{day:02}")
}

fn format_date_time(seconds: i64) -> String {
    if seconds <= 0 {
        return "—".to_string();
    }
    let (year, month, day) = civil_from_unix(seconds);
    let rest = seconds.rem_euclid(86_400);
    format!(
        "{year:04}-{month:02}-{day:02} {:02}:{:02}",
        rest / 3600,
        (rest % 3600) / 60
    )
}

/// Unix seconds to a civil date, per Howard Hinnant's `civil_from_days`.
///
/// Written out rather than pulled in: the crate needs exactly this and nothing
/// else a date library would bring with it.
fn civil_from_unix(seconds: i64) -> (i64, u32, u32) {
    let days = seconds.div_euclid(86_400) + 719_468;

    let era = if days >= 0 { days } else { days - 146_096 } / 146_097;
    let day_of_era = days - era * 146_097;
    let year_of_era =
        (day_of_era - day_of_era / 1460 + day_of_era / 36524 - day_of_era / 146_096) / 365;
    let year = year_of_era + era * 400;
    let day_of_year = day_of_era - (365 * year_of_era + year_of_era / 4 - year_of_era / 100);
    let mp = (5 * day_of_year + 2) / 153;

    let day = (day_of_year - (153 * mp + 2) / 5 + 1) as u32;
    let month = if mp < 10 { mp + 3 } else { mp - 9 } as u32;

    (year + i64::from(month <= 2), month, day)
}


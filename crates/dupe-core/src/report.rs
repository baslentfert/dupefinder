    #[test]
    fn a_path_containing_the_separator_stays_in_one_column() {
        // Folder names with commas are ordinary, and an unquoted one would
        // silently shift every later column.
        let awkward = "C:\\Reports, final\\a\"b\".txt";

        let quoted = csv_field(awkward, ',');
        assert!(quoted.starts_with('"') && quoted.ends_with('"'));
        assert!(quoted.contains("a\"\"b\"\""), "{quoted}");

        // Nothing special in it means no quoting at all.
        assert_eq!(csv_field("plain path", ';'), "plain path");
    }


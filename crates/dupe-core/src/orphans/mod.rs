//! Orphan detection: files nothing owns any more.
//!
//! Unlike duplicate detection, "orphaned" is a claim about the *rest of the
//! system*, not about the file itself, so every detector here can be wrong in
//! a way a hash never is. Findings therefore carry a [`Confidence`] and a
//! human-readable [`OrphanFinding::reason`], and the UI never preselects
//! anything below [`Confidence::Certain`].
//!
//! Three detectors, in decreasing order of how sure they can be:
//!
//! * [`shortcuts`] — a `.lnk` whose target does not exist. Directly
//!   verifiable, so findings are certain.
//! * [`empty`] — directories with nothing in them. Also directly verifiable.
//! * [`installer`] — `.msi` / `.msp` files in the Windows installer cache
//!   that no installed product references. Registry-driven, and the detector
//!   refuses to report anything at all if it cannot read the registry
//!   properly, because "found no references" and "could not look" would
//!   otherwise be indistinguishable and catastrophic.
//! * [`appdata`] — leftover application data from software that is no longer
//!   installed. Purely heuristic: a name match against the uninstall
//!   registry. Always reported as merely suspected.

pub mod appdata;
pub mod empty;
pub mod installer;
pub mod shortcuts;

#[cfg(windows)]
pub mod registry;

use std::path::PathBuf;

use serde::{Deserialize, Serialize};

use crate::error::Result;
use crate::progress::Reporter;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum OrphanKind {
    BrokenShortcut,
    EmptyFolder,
    LeftoverAppData,
    OrphanedInstallerPackage,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum Confidence {
    /// A heuristic guess. Never preselected; the user has to read the reason.
    Suspected,
    /// Strong evidence, but the system could still surprise us.
    Likely,
    /// Directly verified against the file system.
    Certain,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct OrphanFinding {
    pub id: u64,
    pub kind: OrphanKind,
    pub path: PathBuf,
    /// For a directory, the recursive total.
    pub size_bytes: u64,
    pub is_directory: bool,
    pub confidence: Confidence,
    /// Why this was flagged, in words the user can check.
    pub reason: String,
    /// Most recent modification found, seconds since the epoch.
    pub last_modified: Option<i64>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct OrphanConfig {
    /// Where to look for shortcuts and empty folders. The other two detectors
    /// derive their own locations from the system.
    pub roots: Vec<PathBuf>,

    pub broken_shortcuts: bool,
    pub empty_folders: bool,
    pub leftover_appdata: bool,
    pub orphaned_installer: bool,

    /// Application data folders touched more recently than this are assumed
    /// to belong to something still in use, however the name matching went.
    pub appdata_untouched_days: u32,

    /// Treat a folder holding only `desktop.ini` / `thumbs.db` as empty.
    /// Those are generated by Explorer, not by the user.
    pub ignore_shell_metadata: bool,
}

impl Default for OrphanConfig {
    fn default() -> Self {
        Self {
            roots: Vec::new(),
            broken_shortcuts: true,
            empty_folders: true,
            leftover_appdata: true,
            orphaned_installer: true,
            appdata_untouched_days: 180,
            ignore_shell_metadata: true,
        }
    }
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct OrphanReport {
    pub findings: Vec<OrphanFinding>,
    /// Detectors that could not run, and why. Surfaced in the UI so an empty
    /// result is never mistaken for a clean system.
    pub unavailable: Vec<DetectorUnavailable>,
    pub reclaimable_bytes: u64,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DetectorUnavailable {
    pub kind: OrphanKind,
    pub reason: String,
}

/// Run the enabled detectors.
pub fn find(cfg: &OrphanConfig, reporter: &Reporter) -> Result<OrphanReport> {
    let mut report = OrphanReport::default();

    if cfg.broken_shortcuts {
        match shortcuts::find(cfg, reporter) {
            Ok(found) => report.findings.extend(found),
            Err(err) => report.unavailable.push(DetectorUnavailable {
                kind: OrphanKind::BrokenShortcut,
                reason: err.to_string(),
            }),
        }
    }
    reporter.check_cancelled()?;

    if cfg.empty_folders {
        match empty::find(cfg, reporter) {
            Ok(found) => report.findings.extend(found),
            Err(err) => report.unavailable.push(DetectorUnavailable {
                kind: OrphanKind::EmptyFolder,
                reason: err.to_string(),
            }),
        }
    }
    reporter.check_cancelled()?;

    if cfg.leftover_appdata {
        match appdata::find(cfg, reporter) {
            Ok(found) => report.findings.extend(found),
            Err(err) => report.unavailable.push(DetectorUnavailable {
                kind: OrphanKind::LeftoverAppData,
                reason: err.to_string(),
            }),
        }
    }
    reporter.check_cancelled()?;

    if cfg.orphaned_installer {
        match installer::find(reporter) {
            Ok(found) => report.findings.extend(found),
            Err(err) => report.unavailable.push(DetectorUnavailable {
                kind: OrphanKind::OrphanedInstallerPackage,
                reason: err.to_string(),
            }),
        }
    }

    // Most to gain first, and within that the surest findings first.
    report.findings.sort_by(|a, b| {
        b.confidence
            .cmp(&a.confidence)
            .then_with(|| b.size_bytes.cmp(&a.size_bytes))
            .then_with(|| a.path.cmp(&b.path))
    });
    for (i, finding) in report.findings.iter_mut().enumerate() {
        finding.id = i as u64 + 1;
    }

    report.reclaimable_bytes = report.findings.iter().map(|f| f.size_bytes).sum();
    Ok(report)
}

/// Recursive size of a directory, and the newest modification time in it.
pub(crate) fn measure_directory(path: &std::path::Path) -> (u64, Option<i64>) {
    let mut bytes = 0u64;
    let mut newest: Option<i64> = None;

    for entry in ignore::WalkBuilder::new(path)
        .standard_filters(false)
        .follow_links(false)
        .build()
        .flatten()
    {
        let Ok(meta) = entry.metadata() else {
            continue;
        };
        if meta.is_file() {
            bytes += meta.len();
        }
        let mtime = crate::scan::walk::mtime_secs(&meta);
        newest = Some(newest.map_or(mtime, |n: i64| n.max(mtime)));
    }

    (bytes, newest)
}
